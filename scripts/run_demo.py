class Run:
    def __init__(self) -> None:
        init_db()
        self.client = TestClient(create_app())
        self.files: list[str] = []

    def call(self, method: str, path: str, headers: dict[str, str], body: Any = None, expect_ok: bool = True) -> Any:
        response = self.client.request(method, path, json=body, headers=headers)
        if expect_ok and response.status_code >= 300:
            raise SystemExit(f"{method} {path} failed with {response.status_code}: {response.text[:600]}")
        return response.json() if response.headers.get("content-type", "").startswith("application/json") else response.text

    def write(self, name: str, body: str) -> None:
        path = ARGS.outputs / name
        if name.endswith(".md"):
            body = f"<!-- Generated by scripts/run_demo.py on {RUN_AT}. {MODE_NOTE} -->\n\n{body.strip()}\n"
        elif name.endswith(".html"):
            body = f"<!-- Generated by scripts/run_demo.py on {RUN_AT}. {MODE_NOTE} -->\n{body}"
        path.write_text(body, encoding="utf-8")
        self.files.append(name)

    def artifact(self, base: str, headers: dict[str, str], kind: str) -> dict[str, Any]:
        items = [a for a in self.call("GET", f"{base}/artifacts", headers) if a["kind"] == kind]
        if not items:
            raise SystemExit(f"Artifact {kind} missing")
        return self.call("GET", f"{base}/artifacts/{items[-1]['id']}", headers)


def transcript_md(messages: list[dict[str, Any]], title: str) -> str:
    lines = [f"# {title}", "", "Claims inside agent replies are reasoning, not sourced facts: treat them as ASSUMPTION unless a source URL is cited.", ""]
    for m in messages:
        if m["role"] == "founder":
            lines += [f"**Founder:** {m['content']}", ""]
        elif m["role"] == "system":
            lines += [f"*{m['content']}*", ""]
        else:
            s = m.get("structured") or {}
            who = "Policy guard" if s.get("policy") else "Mate"
            stance = s.get("stance") or s.get("position") or ""
            lines += [f"**{who}** ({stance}): {m['content']}", ""]
            if s.get("key_question"):
                lines += [f"> Key question: {s['key_question']}", ""]
            for a in s.get("assumptions") or []:
                lines.append(f"- `{a['classification']}` {a['statement']}")
            if s.get("assumptions"):
                lines.append("")
    return "\n".join(lines)


def gate(run: Run, base: str, headers: dict[str, str], phase: int, name: str) -> dict[str, Any]:
    result = run.call("POST", f"{base}/phases/{phase}/gate", headers)
    run.write(name, run.artifact(base, headers, "gate_decision")["content"])
    return result["gate"]


