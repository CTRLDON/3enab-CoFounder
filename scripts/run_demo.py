"""Runs the demonstration end to end through Mate's real API and writes outputs/ and decision_log.json.

    python scripts/run_demo.py                 # scripted demo mode (no model needed)
    python scripts/run_demo.py --mode live     # same founder inputs, agent replies from the live model
                                               # (MODEL_PROVIDER + GEMINI_API_KEY, or a local Ollama)

In both modes the founder's inputs come from the demo script (a synthetic founder). In demo mode the
agents' replies are scripted fixtures; in live mode they come from the configured live model (Gemini API or Ollama). Everything else —
state machine, approvals, deterministic gates, research retrieval attempts, MVP build and tests,
MOCKED commerce and the decision log — runs for real. Every output file states which mode produced it.
"""

